/**
 * Generates src/ref/palette.json from palette.config.ts.
 * Run after changing the config: `npm run palette`.
 */
import { writeFileSync } from 'node:fs'
import { hexToLch, hexToRgb, lchToHex, type Hex } from '../lib/color.ts'
import { grays, hues, neutralChroma, neutralHue, neutrals } from '../palette.config.ts'

const OUTPUT = new URL('../src/ref/palette.json', import.meta.url)

const colorValue = (hex: Hex) => ({
  colorSpace: 'srgb',
  components: hexToRgb(hex).map((channel) => Number(channel.toFixed(4))),
  hex,
})

const token = (hex: Hex, description?: string) => ({
  $value: colorValue(hex),
  ...(description && { $description: description }),
})

const byTone = <T>(entries: [number, T][]) => Object.fromEntries(entries.sort(([a], [b]) => a - b).map(([tone, value]) => [String(tone), value]))

const palette: Record<string, unknown> = {
  $description: 'Generated by scripts/palette.ts from palette.config.ts. Do not edit by hand.',
  $type: 'color',
  white: token('#FFFFFF'),
  black: token('#000000'),
  gray: {
    $description: grays.description,
    ...byTone(grays.tones.map((tone) => [tone, token(lchToHex({ l: tone, c: 0, h: 0 }))])),
  },
}

for (const [name, family] of Object.entries(neutrals)) {
  const generate = (tone: number) =>
    lchToHex({ l: tone, c: Math.max(0, neutralChroma(tone) * family.chromaScale + family.chromaOffset), h: neutralHue(tone) })
  palette[name] = { $description: family.description, ...byTone(family.tones.map((tone) => [tone, token(generate(tone))])) }
}

for (const [name, family] of Object.entries(hues)) {
  const anchors = Object.entries(family.anchors).map(([tone, hex]) => [Number(tone), token(hex)] as [number, ReturnType<typeof token>])
  const derived = Object.entries(family.derived ?? {}).map(([tone, { from, reason, chroma }]) => {
    const source = hexToLch(family.anchors[from])
    return [Number(tone), token(lchToHex({ ...source, l: Number(tone), c: chroma ?? source.c }), reason)] as [number, ReturnType<typeof token>]
  })
  palette[name] = { $description: family.description, ...byTone([...anchors, ...derived]) }
}

writeFileSync(OUTPUT, `${JSON.stringify({ palette }, null, 2)}\n`)
console.log(`palette → ${OUTPUT.pathname}`)
