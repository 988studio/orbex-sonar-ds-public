const budgetOf = (name: string) => BUDGETS[name] ?? BUDGET

const components = readdirSync(src, { withFileTypes: true })
  .filter((entry) => entry.isDirectory() && entry.name !== 'internal')
  .map((entry) => entry.name)
  .sort()

/* ---------- Scripts and declarations ---------- */

rmSync(dist, { recursive: true, force: true })
execFileSync('npx', ['tsc', '-p', 'tsconfig.json'], { cwd: root, stdio: 'inherit' })

/* ---------- Styles ---------- */

const styles = components.map((name) => {
  const file = new URL(`${name}/styles.css`, src)
  if (!existsSync(file)) throw new Error(`${name} has no styles.css`)
  cpSync(file, new URL(`${name}/styles.css`, dist))
  return readFileSync(file, 'utf8')
})
writeFileSync(new URL('styles.css', dist), [HEADER, '@layer sonar.tokens, sonar.components;', ...styles].join('\n\n'))

/* ---------- API ---------- */

interface Prop { name: string; type: string; required: boolean; default?: string; description: string }
interface Part { name: string; description: string; props: Prop[]; extends?: string }

const program = ts.createProgram(
  components.map((name) => new URL(`${name}/index.ts`, src).pathname),
  { jsx: ts.JsxEmit.ReactJSX, allowImportingTsExtensions: true, noEmit: true, strict: true, moduleResolution: ts.ModuleResolutionKind.Bundler, module: ts.ModuleKind.ESNext, target: ts.ScriptTarget.ES2022 },
)

/* Binding sets parent pointers, which JSDoc lookups and getText need */
program.getTypeChecker()

const docOf = (node: ts.Node) =>
  ts.getJSDocCommentsAndTags(node).filter(ts.isJSDoc).map((doc) => ts.getTextOfJSDocComment(doc.comment) ?? '').join('\n').replace(/\s*\n\s*/g, ' ').trim()

const defaultOf = (node: ts.Node) => {
  const tag = ts.getJSDocTags(node).find((candidate) => candidate.tagName.text === 'default')
  return tag ? ts.getTextOfJSDocComment(tag.comment)?.trim() : undefined
}

const compact = (text: string) => text.replace(/\s+/g, ' ').trim()

/* Props of an interface, including those of interfaces it extends from the same file (FieldFrameProps) */
function propsOf(declaration: ts.InterfaceDeclaration, local: Map<string, ts.InterfaceDeclaration>): { props: Prop[]; extends?: string } {
  const inherited = (declaration.heritageClauses ?? []).flatMap((clause) => clause.types)
  const own = inherited.map((type) => local.get(type.expression.getText())).filter((node): node is ts.InterfaceDeclaration => Boolean(node))
  const members = [...own.flatMap((node) => [...node.members]), ...declaration.members]
  const props = members.filter(ts.isPropertySignature).map((member) => ({
    name: member.name.getText(),
    type: compact(member.type?.getText() ?? 'unknown'),
    required: !member.questionToken,
    ...(defaultOf(member) && { default: defaultOf(member) }),
    description: docOf(member),
  }))
  const heritage = inherited.filter((type) => !local.has(type.expression.getText())).map((type) => compact(type.getText())).join(', ')
  return { props, ...(heritage && { extends: heritage }) }
}

const api = components.map((entry) => {
  const files = readdirSync(new URL(entry, src)).filter((file) => file.endsWith('.tsx'))
  const parts: Part[] = []
  let behavior: 'native' | 'base-ui' = 'native'
  for (const file of files) {
    const source = program.getSourceFile(new URL(`${entry}/${file}`, src).pathname)!
    if (source.text.includes('@base-ui/react')) behavior = 'base-ui'
    const interfaces = new Map(source.statements.filter(ts.isInterfaceDeclaration).map((node) => [node.name.text, node]))
    for (const statement of source.statements) {
      if (!ts.isFunctionDeclaration(statement) || !statement.name || !/^[A-Z]/.test(statement.name.text)) continue
      const name = statement.name.text
      const exported = statement.modifiers?.some((modifier) => modifier.kind === ts.SyntaxKind.ExportKeyword)
      const compound = /export const \w+ = \{/.test(source.text)
      if (!exported && !compound) continue
      const typeName = statement.parameters[0]?.type?.getText()
      /* A generic props interface (SearchFieldProps<Item>) is declared under its bare name */
      const declaration = typeName ? interfaces.get(typeName.replace(/<.*$/, '')) : undefined
      const typeAlias = typeName && source.statements.find((node): node is ts.TypeAliasDeclaration => ts.isTypeAliasDeclaration(node) && node.name.text === typeName)
      parts.push({
        name,
        description: docOf(statement),
        ...(declaration ? propsOf(declaration, interfaces) : { props: [], ...(typeName && { extends: compact(typeAlias ? typeAlias.type.getText() : typeName) }) }),
      })
    }
  }
  const compoundName = readFileSync(new URL(`${entry}/index.ts`, src), 'utf8').match(/export \{ (\w+)/)?.[1]
  return { entry, name: compoundName, behavior, parts }
})

writeFileSync(new URL('api.json', dist), `${JSON.stringify({ components: api }, null, 2)}\n`)

/* ---------- Size ---------- */

const sizeOf = (file: URL) => gzipSync(readFileSync(file)).length
const report = components.map((name) => {
  const scripts = readdirSync(new URL(name, dist)).filter((file) => file.endsWith('.js'))
  const js = scripts.reduce((sum, file) => sum + sizeOf(new URL(`${name}/${file}`, dist)), 0)
  const css = sizeOf(new URL(`${name}/styles.css`, dist))
  return { name, js, css, total: js + css }
})
const over = report.filter(({ name, total }) => total > budgetOf(name))
for (const { name, js, css, total } of report) console.log(`${name.padEnd(18)} js ${String(js).padStart(5)} B  css ${String(css).padStart(5)} B  ${total > budgetOf(name) ? 'OVER BUDGET' : ''}`)
writeFileSync(new URL('sizes.json', dist), `${JSON.stringify({ budget: BUDGET, components: report.map((entry) => ({ ...entry, budget: budgetOf(entry.name) })) }, null, 2)}\n`)
if (over.length) throw new Error(`Over budget: ${over.map(({ name, total }) => `${name} (${total} of ${budgetOf(name)} B)`).join(', ')}`)
console.log(`${components.length} components → ${dist.pathname}`)
