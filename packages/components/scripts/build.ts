/**
 * Builds the components package:
 *   dist/<component>/index.js + .d.ts   one entry point per component (compiled by tsc, modules preserved)
 *   dist/<component>/styles.css         that component's styles, in the `sonar.components` cascade layer
 *   dist/styles.css                     every component's styles, for apps that use most of them
 *   dist/api.json                       the props of every component, read from the source (documentation, agents)
 * and fails when a component outgrows its size budget.
 */
